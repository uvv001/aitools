#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { rolldown } from 'rolldown';
import { syncReadmeCommandReference } from '../src/help-catalog.ts';

const ROOT = resolve(import.meta.dirname, '..');
const DEFAULT_OUT = resolve(ROOT, '..', '..', 'skills', 'review-with-docs', 'pr-comments.mjs');
const DEFAULT_README = resolve(ROOT, 'README.md');
const BANNER = '// Generated by "pnpm build" from the pr-comments sources; do not edit.';

function git(cwd: string, ...args: string[]): string | undefined {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return undefined;
  }
}

// Updates README.md's generated Command reference section when it differs from the catalog; leaves the file untouched when already in sync.
export async function syncReadme(readmePath: string = DEFAULT_README): Promise<boolean> {
  const current = await readFile(readmePath, 'utf8');
  const next = syncReadmeCommandReference(current);
  if (next === current) return false;
  await writeFile(readmePath, next, 'utf8');
  return true;
}

// The commit the bundle is built from, with "-dirty" when tracked files under `root` (`tools/pr-comments/`) have
// uncommitted changes; empty without git.
export function buildId(root: string = ROOT): string {
  const commit = git(root, 'rev-parse', '--short', 'HEAD');
  if (!commit) return '';
  return git(root, 'status', '--porcelain', '--untracked-files=no', '--', '.') ? `${commit}-dirty` : commit;
}

// Bundles the CLI and everything it imports into one ES module that needs nothing but Node (node: built-ins stay imports).
export async function buildBundle(out?: string, build?: string): Promise<string> {
  if (out === undefined) await syncReadme();
  const effectiveBuild = build ?? buildId();
  const file = resolve(out ?? DEFAULT_OUT);
  await mkdir(dirname(file), { recursive: true });
  const bundle = await rolldown({
    input: resolve(ROOT, 'src', 'cli.ts'),
    platform: 'node',
    transform: { define: { __BUILD__: JSON.stringify(effectiveBuild) } },
    logLevel: 'warn',
  });
  try {
    await bundle.write({ file, format: 'esm', banner: BANNER });
  } finally {
    await bundle.close();
  }
  return file;
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { out: { type: 'string' }, build: { type: 'string' } } });
  buildBundle(values.out, values.build)
    .then((file) => console.log(`Built ${file}`))
    .catch((error: unknown) => {
      console.error(error instanceof Error ? error.message : error);
      process.exitCode = 1;
    });
}
