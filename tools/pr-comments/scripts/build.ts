#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { rolldown } from 'rolldown';

const ROOT = resolve(import.meta.dirname, '..');
const DEFAULT_OUT = resolve(ROOT, 'dist', 'pr-comments.mjs');
const BANNER = '// Generated by "pnpm build" from the pr-comments sources; do not edit.';

function git(...args: string[]): string | undefined {
  try {
    return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return undefined;
  }
}

// The commit the bundle is built from, with "-dirty" when tracked files have uncommitted changes; empty without git.
export function buildId(): string {
  const commit = git('rev-parse', '--short', 'HEAD');
  if (!commit) return '';
  return git('status', '--porcelain', '--untracked-files=no') ? `${commit}-dirty` : commit;
}

// Bundles the CLI and everything it imports into one ES module that needs nothing but Node (node: built-ins stay imports).
export async function buildBundle(out: string = DEFAULT_OUT, build: string = buildId()): Promise<string> {
  const file = resolve(out);
  await mkdir(dirname(file), { recursive: true });
  const bundle = await rolldown({
    input: resolve(ROOT, 'src', 'cli.ts'),
    platform: 'node',
    transform: { define: { __BUILD__: JSON.stringify(build) } },
    logLevel: 'warn',
  });
  try {
    await bundle.write({ file, format: 'esm', banner: BANNER });
  } finally {
    await bundle.close();
  }
  return file;
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { out: { type: 'string' }, build: { type: 'string' } } });
  buildBundle(values.out, values.build)
    .then((file) => console.log(`Built ${file}`))
    .catch((error: unknown) => {
      console.error(error instanceof Error ? error.message : error);
      process.exitCode = 1;
    });
}
