import { describe, expect, it } from 'vitest';
import { buildDashboard } from './report-dashboard.ts';
import type { DashboardFinding } from './review-model.ts';
import { slug } from './review-render.ts';

const GENERATED = '<!-- generated by pr-comments — do not edit by hand -->';
const NONE = '**No findings** — the review raised none.';

const HEADERS = [
  '⏳ 🔴 F1 — Unguarded `resource.value()` crashes',
  '🔧 🟡 F2 — Second',
  '⏳ ⚪ F3 — Third',
  '❌ 🔴 F4 — Fourth',
  '🔧 🔴 F5 — Fifth',
  '🔀 ⚪ F6 — Sixth',
];

const EXPECTED_DASHBOARD = [
  '## Dashboard',
  '',
  GENERATED,
  '',
  '### ⏳ 2 awaiting triage',
  '',
  '  1. [F1](#--f1--unguarded-resourcevalue-crashes)',
  '  2. [F3](#--f3--third)',
  '',
  '### 🔧 2 fixed',
  '',
  '  1. [F2](#--f2--second)',
  '  2. [F5](#--f5--fifth)',
  '',
  '### ❌ 1 discarded',
  '',
  '  1. [F4](#--f4--fourth)',
  '',
  '### 🔀 1 improvement',
  '',
  '  1. [F6](#--f6--sixth)',
  '',
];

function findingsOf(headers: string[]): DashboardFinding[] {
  return headers.map((header) => {
    const [state = '', , id = ''] = header.split(' ');
    return { id, state, anchor: slug(header) };
  });
}

describe('buildDashboard', () => {
  it('says so when there are no findings', () => {
    expect(buildDashboard([])).toEqual(['## Dashboard', '', GENERATED, '', NONE, '']);
  });

  it('writes one section per state that carries findings, in the order of the scale', () => {
    expect(buildDashboard(findingsOf(HEADERS))).toEqual(EXPECTED_DASHBOARD);
  });

  it('numbers each list from one and counts each state', () => {
    const lines = buildDashboard(findingsOf(['📌 🔴 F1 — a', '📌 🟡 F2 — b', '📌 ⚪ F3 — c']));
    expect(lines).toEqual([
      '## Dashboard',
      '',
      GENERATED,
      '',
      '### 📌 3 deferred',
      '',
      '  1. [F1](#--f1--a)',
      '  2. [F2](#--f2--b)',
      '  3. [F3](#--f3--c)',
      '',
    ]);
  });

  it('labels every state', () => {
    const headers = ['⏳', '❓', '✅', '🔧', '❌', '📌', '🔀'].map((state, index) => `${state} 🔴 F${index + 1} — t`);
    const sections = buildDashboard(findingsOf(headers)).filter((line) => line.startsWith('### '));
    expect(sections).toEqual([
      '### ⏳ 1 awaiting triage',
      '### ❓ 1 unverified',
      '### ✅ 1 approved',
      '### 🔧 1 fixed',
      '### ❌ 1 discarded',
      '### 📌 1 deferred',
      '### 🔀 1 improvement',
    ]);
  });
});
