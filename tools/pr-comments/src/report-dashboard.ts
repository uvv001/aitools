import { STATES, type DashboardFinding } from './review-model.ts';

// The line that marks the generated Dashboard.
const GENERATED = '<!-- generated by pr-comments — do not edit by hand -->';

// The `## Dashboard` section, as lines: one subsection per state that carries findings, each listing numbered links.
export function buildDashboard(findings: DashboardFinding[]): string[] {
  const block = ['## Dashboard', '', GENERATED, ''];
  if (findings.length === 0) {
    block.push('**No findings** — the review raised none.', '');
    return block;
  }
  for (const state of STATES) {
    const listed = findings.filter((finding) => finding.state === state.marker);
    if (listed.length === 0) continue;
    block.push(`### ${state.marker} ${listed.length} ${state.label}`, '');
    listed.forEach((finding, index) => block.push(`  ${index + 1}. [${finding.id}](#${finding.id.toLowerCase()})`));
    block.push('');
  }
  return block;
}
