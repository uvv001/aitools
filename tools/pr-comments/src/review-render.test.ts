import { describe, expect, it } from 'vitest';
import type { Finding, IntroEntry, ReviewData } from './review-model.ts';
import { renderReport, slug } from './review-render.ts';

function entry(...texts: string[]): IntroEntry<{ text: string }> {
  return { items: texts.map((text) => ({ text })) };
}

function finding(number: number, state = '⏳', severity = '🔴', title = `Title ${number}`): Finding {
  return {
    id: `F${number}`,
    state,
    severity,
    title,
    description: `Body of F${number}.`,
    updates: [{ text: '2026-10-05 11:15 — Round 1: raised' }],
  };
}

function data(changes: Partial<ReviewData> = {}): ReviewData {
  return {
    target: 'PR 42',
    intro: {
      reviewed: entry('Round 1 — `abc1234`, base none — reviewed as it stands; tracked tree clean.'),
    },
    findings: [],
    ...changes,
  };
}

const lines = (text: string): string[] => text.split('\n');

describe('renderReport', () => {
  it('writes the title, Reviewed as the only intro entry, the generated dashboard and the findings section', () => {
    const rendered = renderReport(data({ intro: { reviewed: entry('Round 1 — `<revision>`, <base>; <clean or dirty tree>.') } }));
    expect(rendered).toBe(
      [
        '# Review — PR 42',
        '',
        '## Intro',
        '',
        '**Reviewed**',
        '',
        '- Round 1 — `<revision>`, <base>; <clean or dirty tree>.',
        '',
        '## Dashboard',
        '',
        '<!-- generated by pr-comments — do not edit by hand -->',
        '',
        '**No findings** — the review raised none.',
        '',
        '## Findings',
        '',
      ].join('\n'),
    );
  });

  it('writes a Reviewed entry without rounds as the bare label', () => {
    const rendered = renderReport(data({ intro: { reviewed: entry() } }));
    expect(rendered).toBe(
      '# Review — PR 42\n\n## Intro\n\n**Reviewed**\n\n## Dashboard\n\n<!-- generated by pr-comments — do not edit by hand -->\n\n**No findings** — the review raised none.\n\n## Findings\n',
    );
  });

  it('derives the dashboard from the findings', () => {
    const findings = [finding(1), finding(2, '🔧', '🟡'), finding(3, '⏳', '⚪'), finding(4, '❓')];
    const rendered = renderReport(data({ findings }));
    const start = lines(rendered).indexOf('## Dashboard');
    expect(lines(rendered).slice(start, start + 14)).toEqual([
      '## Dashboard',
      '',
      '<!-- generated by pr-comments — do not edit by hand -->',
      '',
      '### ⏳ 2 awaiting triage',
      '',
      '  1. [F1](#--f1--title-1)',
      '  2. [F3](#--f3--title-3)',
      '',
      '### ❓ 1 unverified',
      '',
      '  1. [F4](#--f4--title-4)',
      '',
      '### 🔧 1 fixed',
    ]);
  });

  it('writes the empty dashboard line for a report without findings', () => {
    expect(renderReport(data())).toContain('## Dashboard\n\n<!-- generated by pr-comments — do not edit by hand -->\n\n**No findings** — the review raised none.\n\n## Findings\n');
  });

  it('writes dashboard links whose anchors match slug() for each finding header', () => {
    const titles = [
      'Unguarded `resource.value()` crashes UsersPage',
      'Café “smart quotes” & <tags> [links](x) #hash 100% done?!',
      'snake_case-and-kebab + ALL CAPS 日本語 🎉',
      'two  spaces and — dashes —',
    ];
    const findings = titles.map((title, index) => finding(index + 1, ['⏳', '✅', '🔧', '❓'][index], '🟡', title));
    const rendered = renderReport(data({ findings }));
    for (const item of findings) {
      const header = `${item.state} ${item.severity} ${item.id} — ${item.title}`;
      expect(rendered).toContain(`[${item.id}](#${slug(header)})`);
      expect(rendered).toContain(`### ${header}`);
    }
  });

  it('ends every line, the last one too, with LF', () => {
    const rendered = renderReport(data({ findings: [finding(1), finding(2, '✅')] }));
    expect(rendered.endsWith('\n')).toBe(true);
    expect(rendered).not.toContain('\r');
  });

  it('separates the findings by one blank line and ends after the last update', () => {
    const rendered = renderReport(data({ findings: [finding(1), finding(2)] }));
    expect(rendered.slice(rendered.indexOf('## Findings'))).toBe(
      [
        '## Findings',
        '',
        '### ⏳ 🔴 F1 — Title 1',
        '',
        '#### Description',
        '',
        'Body of F1.',
        '',
        '#### Updates',
        '',
        '- 2026-10-05 11:15 — Round 1: raised',
        '',
        '### ⏳ 🔴 F2 — Title 2',
        '',
        '#### Description',
        '',
        'Body of F2.',
        '',
        '#### Updates',
        '',
        '- 2026-10-05 11:15 — Round 1: raised',
        '',
      ].join('\n'),
    );
  });

  it('writes the subsections of a finding without description or updates', () => {
    const empty: Finding = { ...finding(1), description: '', updates: [] };
    const rendered = renderReport(data({ findings: [empty] }));
    expect(rendered.slice(rendered.indexOf('## Findings'))).toBe(
      '## Findings\n\n### ⏳ 🔴 F1 — Title 1\n\n#### Description\n\n#### Updates\n',
    );
  });

  it('writes multi-line texts verbatim', () => {
    const multi: Finding = {
      ...finding(1),
      description: 'a\n\n```\n#### Updates\n```',
      updates: [{ text: '2026-10-05 11:15 — Round 1: raised\n  continued' }],
    };
    expect(renderReport(data({ findings: [multi] }))).toContain(
      '#### Description\n\na\n\n```\n#### Updates\n```\n\n#### Updates\n\n- 2026-10-05 11:15 — Round 1: raised\n  continued\n',
    );
  });

  it('writes the label of the entry on its own line, the items as bullets below it', () => {
    const forms: [IntroEntry<{ text: string }>, string[]][] = [
      [entry('Round 1 — x', 'Round 2 — y'), ['**Reviewed**', '', '- Round 1 — x', '- Round 2 — y']],
      [entry('Round 1 — x'), ['**Reviewed**', '', '- Round 1 — x']],
      [entry(), ['**Reviewed**']],
    ];
    for (const [reviewed, written] of forms) {
      const rendered = renderReport(data({ intro: { reviewed } }));
      expect(rendered).toContain(['## Intro', '', ...written, '', '## Dashboard'].join('\n'));
    }
  });

  it('never needs the derived fields of the items', () => {
    const derived = data({
      intro: {
        reviewed: { items: [{ text: 'Round 1 — `abc1234`, base `def5678`; clean.', round: 1, revision: 'abc1234', base: 'def5678' }] },
      },
      findings: [{ ...finding(1), updates: [{ text: '2026-10-05 11:15 — Round 1: raised', at: '2026-10-05 11:15', round: 1 }] }],
    });
    const bare = JSON.parse(JSON.stringify(derived, (key, value) => (['round', 'revision', 'base', 'at'].includes(key) ? undefined : value)));
    expect(renderReport(bare)).toBe(renderReport(derived));
  });

  it('renders every state and severity', () => {
    const findings = ['⏳', '❓', '✅', '🔧', '❌', '📌', '🔀'].map((state, index) => finding(index + 1, state, ['🔴', '🟡', '⚪'][index % 3]));
    const rendered = renderReport(data({ findings }));
    for (const item of findings) {
      expect(rendered).toContain(`### ${item.state} ${item.severity} ${item.id} — ${item.title}`);
    }
  });
});

describe('slug', () => {
  it('drops markers, punctuation and code ticks and turns each space into a hyphen', () => {
    expect(slug('✅ 🔴 F4 — Icon-only settings button has no accessible name')).toBe(
      '--f4--icon-only-settings-button-has-no-accessible-name',
    );
    expect(slug('⏳ 🟡 F10 — Fix `foo_bar()` (and "baz")')).toBe('--f10--fix-foo_bar-and-baz');
    expect(slug('🔧 ⚪ F2 — Uses v1.2.3: really?!')).toBe('--f2--uses-v123-really');
  });

  it('lower-cases and keeps Unicode letters, marks, digits, spaces, underscores and hyphens', () => {
    expect(slug('❓ 🔴 F3 — Café Déjà Vu — 日本語 2² + 🎉')).toBe('--f3--café-déjà-vu--日本語-2--');
    expect(slug('📌 🟡 F5 — ALL CAPS and snake_case-and-kebab')).toBe('--f5--all-caps-and-snake_case-and-kebab');
  });

  it('strips inline Markdown markup outside code spans when building the anchor', () => {
    expect(slug('⏳ ⚪ F1 — _Emphasized_, __strong__, and [Documentation](https://example.com/a_(b_(c))/d)')).toBe(
      '--f1--emphasized-strong-and-documentation',
    );
    expect(slug('🔧 🔴 F2 — Commit subject does not follow <category>: <entity> format')).toBe(
      '--f2--commit-subject-does-not-follow---format',
    );
    expect(slug('🔧 🔴 F3 — Commit subject does not follow `<category>`: `_entity_` format')).toBe(
      '--f3--commit-subject-does-not-follow-category-_entity_-format',
    );
    expect(slug('⏳ ⚪ F4 — Link with [`code_span`](https://example.com) and ![alt](https://example.com/a.png)')).toBe(
      '--f4--link-with-code_span-and-',
    );
    expect(slug('⏳ ⚪ F5 — <https://example.com/path>, <file.sqlite>, Use \\_literal_, and __outer _inner_ end__')).toBe(
      '--f5--httpsexamplecompath-filesqlite-use-_literal_-and-outer-inner-end',
    );
    expect(slug('⏳ ⚪ F6 — [Angle](<https://example.com/a)tail>) and [Titled](https://example.com/a_(b) "note) end")')).toBe(
      '--f6--angle-and-titled',
    );
  });

  it('keeps consecutive spaces as consecutive hyphens', () => {
    expect(slug('🔀 ⚪ F6 — two  spaces')).toBe('--f6--two--spaces');
  });
});
